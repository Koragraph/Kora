import { defineConfig } from "vite-plus";

// The chat UI server is not a process: `vp pack` bundles src/index.ts — Effect, @effect/platform-node and
// @kora/contracts inlined — into ONE CommonJS file under packages/runtime/ui (a build artifact, not committed),
// which `kora server run` requires and starts on its UI port (packages/runtime/src/server/ui.ts). The runtime
// then builds with plain tsc and installs standalone. `pnpm build` runs this; after changing anything here run
// `pnpm --filter @kora/ui-server bundle` and restart the daemon. KORA_UI_BUNDLE_OUT overrides the destination.
const outDir = process.env.KORA_UI_BUNDLE_OUT ?? "../runtime/ui";

export default defineConfig({
  pack: {
    format: "cjs",
    platform: "node",
    target: "node22",
    outDir,
    dts: false,
    // Shipped minified, names kept (server.log stack traces stay readable); the .map stays in packages/runtime/ui and
    // package-app.sh strips *.map from the app.
    sourcemap: true,
    clean: false,
    entry: { "ui-server": "src/index.ts" },
    outExtensions: () => ({ js: ".cjs" }),
    outputOptions: {
      codeSplitting: false,
      minify: true,
      keepNames: true,
      banner:
        "// GENERATED by packages/ui-server (`pnpm --filter @kora/ui-server bundle`) — do not edit.\n" +
        "// The chat UI server loaded by `kora server run` (src/server/ui.ts).",
    },
    deps: {
      alwaysBundle: (id: string) => !id.startsWith("node:"),
      onlyBundle: false,
    },
  },
});
