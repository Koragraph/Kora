// Compiles the Tailwind utilities used by the in-page annotation overlay into a TS string module,
// so the pick preload can inject the styles without shipping a stylesheet.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const appRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const requireHere = createRequire(import.meta.url);
const { compile } = await import("tailwindcss");

const tailwindDir = dirname(requireHere.resolve("tailwindcss/package.json"));
const overlaySource = readFileSync(join(appRoot, "src/web/Annotation.css"), "utf8");
const preloadSource = readFileSync(join(appRoot, "src/web/PickPreload.ts"), "utf8");

// Deliberately generous: every class-looking token is offered; the ones nothing uses emit no CSS.
const classTokens = new Set(preloadSource.match(/!?-?[A-Za-z0-9_:@/.[\]()%,-]+/g) ?? []);

const stylesheet = [
  readFileSync(join(tailwindDir, "theme.css"), "utf8"),
  readFileSync(join(tailwindDir, "preflight.css"), "utf8"),
  overlaySource.replace('@import "tailwindcss";', "@tailwind utilities;"),
].join("\n");

const compiler = await compile(stylesheet, { base: appRoot });
const css = compiler.build([...classTokens]);

const literal = css
  .replace(/\\/g, "\\\\")
  .replace(/'/g, "\\'")
  .replace(/\r/g, "\\r")
  .replace(/\n/g, "\\n");
writeFileSync(
  join(appRoot, "src/web/MarkupStyles.generated.ts"),
  `// Generated by scripts/build-markup-css.mjs. Do not edit.\nexport const webMarkupStyles =\n  '${literal}';\n`,
);
